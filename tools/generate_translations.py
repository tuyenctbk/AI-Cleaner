# Read master strings.xml
master_path = "app/src/main/res/values/strings.xml"
with open(master_path, "r", encoding="utf-8") as f:
    master_content = f.read()

pattern = re.compile(r'<string\s+name="([^"]+)"(?:\s+formatted="([^"]+)")?\s*>(.*?)</string>', re.DOTALL)
master_items = []
for m in pattern.finditer(master_content):
    name = m.group(1)
    fmt = m.group(2)
    val = m.group(3)
    master_items.append((name, val, fmt == "false"))

print(f"Master contains {len(master_items)} strings.")

# Load existing translations for each locale to preserve existing good translations
existing_translations = {}
for loc in LOCALES:
    loc_file = f"app/src/main/res/values-{loc}/strings.xml"
    existing_translations[loc] = {}
    if os.path.exists(loc_file):
        try:
            with open(loc_file, "r", encoding="utf-8") as f:
                content = f.read()
            for m in pattern.finditer(content):
                existing_translations[loc][m.group(1)] = m.group(3)
        except Exception as e:
            print(f"Error reading {loc}: {e}")

