master_entries = []
for m in pattern.finditer(master_content):
    name = m.group(1)
    fmt = m.group(2)
    val = m.group(3)
    master_entries.append((name, val, fmt == "false"))

print(f"Total master strings: {len(master_entries)}")

# Load existing translations
existing = {}
for loc in LOCALES:
    existing[loc] = {}
